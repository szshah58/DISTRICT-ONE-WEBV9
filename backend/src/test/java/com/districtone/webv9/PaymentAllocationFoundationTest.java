  @Test void concurrentReservationsCannotExceedRemainingDue() throws Exception {
    receivable(1, 200, 300, 1, "100.00", "0.00", "0.00", "0.00");
    jdbc.update("INSERT INTO payments_receipts(id,customer_id,amount,status) VALUES (1,10,60,'RECOVERY_ENTRY'),(2,10,60,'RECOVERY_ENTRY')");
    CountDownLatch ready = new CountDownLatch(2);
    CountDownLatch go = new CountDownLatch(1);
    ExecutorService pool = Executors.newFixedThreadPool(2);
    try {
      Future<Boolean> a = pool.submit(() -> attempt(1L, ready, go));
      Future<Boolean> b = pool.submit(() -> attempt(2L, ready, go));
      ready.await();
      go.countDown();
      assertThat((a.get() ? 1 : 0) + (b.get() ? 1 : 0)).isEqualTo(1);
      assertThat(jdbc.queryForObject("SELECT SUM(allocated_amount) FROM webv9_payment_allocations WHERE receivable_id=1", BigDecimal.class))
          .isEqualByComparingTo("60.00");
    } finally {
      pool.shutdownNow();
    }
  }

