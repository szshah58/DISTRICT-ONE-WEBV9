  @Test void concurrentRecoveryEntriesCannotReserveMoreThanAvailableDue() throws Exception {
    receivable(1, 200, 300, 1, "100.00", "0.00", "0.00", "0.00");
    CountDownLatch ready = new CountDownLatch(2);
    CountDownLatch go = new CountDownLatch(1);
    AtomicInteger sequence = new AtomicInteger();
    ExecutorService pool = Executors.newFixedThreadPool(2);
    try {
      Future<Boolean> first = pool.submit(() -> createConcurrentRecovery(ready, go, sequence));
      Future<Boolean> second = pool.submit(() -> createConcurrentRecovery(ready, go, sequence));
      ready.await();
      go.countDown();
      assertThat((first.get() ? 1 : 0) + (second.get() ? 1 : 0)).isEqualTo(1);
      assertThat(jdbc.queryForObject("SELECT COALESCE(SUM(allocated_amount),0) FROM webv9_payment_allocations", BigDecimal.class))
          .isEqualByComparingTo("60.00");
      assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM payments_receipts", Integer.class)).isEqualTo(1);
    } finally {
      pool.shutdownNow();
    }
  }

